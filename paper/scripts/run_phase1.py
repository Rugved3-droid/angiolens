"""Regenerate every Phase 1 result (E1, E1b, E2, E3, E5) from scratch, sequentially (GPU work never overlaps E5's timings).

    .venv\\Scripts\\python paper\\scripts\\run_phase1.py [--skip=e5] [--headed]

Prerequisites (git-ignored, regenerated by the repo's own pipeline, see README): web/public/anatomy/ (atlas X-ray meshes),
assets/anatomy/inspect/great_vessels_probe.json (evaluated atlas centerlines), web/dist/ (npm run build, for E5).
E4 is not run: paper/benchmarks/recommended_views.csv is required and has not been supplied (paper/TODO.md M1).
"""
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PY = sys.executable
skip = {s for a in sys.argv[1:] if a.startswith("--skip=") for s in a[7:].split(",")}
steps = [
    ("e1", [PY, str(HERE / "e1_projection_agreement.py")]),
    ("e1b", [PY, str(HERE / "e1b_render_agreement.py")]),
    ("e2", [PY, str(HERE / "e2_orientation.py")]),
    ("e3", [PY, str(HERE / "e3_distractors.py"), "--rounds=300"]),
    ("e5", ["node", str(HERE / "browser" / "e5_performance.mjs"), "--reps=5", "--seconds=10"] + (["--headed=1"] if "--headed" in sys.argv else [])),
]
for name, cmd in steps:
    if name in skip:
        print(f"- {name}: skipped")
        continue
    print(f"== {name}")
    subprocess.run(cmd, check=True, cwd=HERE)
print("Phase 1 results regenerated in paper/results/")
